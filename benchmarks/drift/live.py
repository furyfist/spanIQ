"""Real-LLM version of the drift scenarios.

Instead of rewriting answers, each scenario changes the pipeline config (which
passages the retriever returns, the system prompt, the model) and a real model
answers. Needs GROQ_API_KEY and the groq extra; calls are retried with the
benchmark judge policy and fail loudly instead of filling in placeholder text.

    python -m benchmarks.drift.run --live --save-traces benchmarks/results_drift/traces
"""

from __future__ import annotations

import os
import random
from dataclasses import dataclass

from benchmarks.drift.scenarios import Item, _record
from benchmarks.runners._judge import with_retry

DEFAULT_MODEL = os.environ.get("SPANIQ_DRIFT_MODEL", "llama-3.1-8b-instant")
_SYSTEM = "Answer the question using only the context. Be concise."


@dataclass(frozen=True)
class PipelineConfig:
    model: str = DEFAULT_MODEL
    system: str = _SYSTEM
    retrieval: str = "normal"
    temperature: float = 0.3


LIVE_CONFIGS = {
    "control": PipelineConfig(),
    "retriever_degraded": PipelineConfig(retrieval="shuffled"),
    "context_truncated": PipelineConfig(retrieval="truncated"),
    "prompt_format_change": PipelineConfig(system=_SYSTEM + " Format the answer as a bullet list."),
    "model_swap": PipelineConfig(model=os.environ.get("SPANIQ_DRIFT_SWAP_MODEL", "gemma2-9b-it")),
    "verbose_drift": PipelineConfig(system="Answer the question in detail, explaining each point."),
}


def _retrieve(item: Item, items: list[Item], mode: str, rng: random.Random) -> str:
    if mode == "shuffled":
        return rng.choice([i for i in items if i is not item]).context
    if mode == "truncated":
        return item.context[:80]
    return item.context


def _client():
    try:
        from groq import Groq
    except ImportError as exc:
        raise ImportError("groq SDK not installed — run: pip install spaniq[groq]") from exc
    api_key = os.environ.get("GROQ_API_KEY")
    if not api_key:
        raise OSError("GROQ_API_KEY not set in environment")
    return Groq(api_key=api_key)


def generate_live(
    items: list[Item],
    config: PipelineConfig,
    n: int,
    seed: int,
    start_index: int = 0,
    client=None,
) -> list[dict]:
    """n traces from a real model under one pipeline config."""
    client = client or _client()
    rng = random.Random(seed)
    records = []
    for i in range(n):
        item = rng.choice(items)
        context = _retrieve(item, items, config.retrieval, rng)
        messages = [
            {"role": "system", "content": config.system},
            {"role": "user", "content": f"Context:\n{context}\n\nQuestion: {item.question}"},
        ]
        resp = with_retry(
            lambda m=messages: client.chat.completions.create(
                model=config.model, messages=m, temperature=config.temperature, max_tokens=400
            )
        )
        answer = resp.choices[0].message.content or ""
        records.append(_record(start_index + i, item.question, context, answer))
    return records


def build_live_stream(
    scenario: str,
    items: list[Item],
    seed: int,
    n_baseline: int = 100,
    n_pre: int = 200,
    n_post: int = 300,
    client=None,
) -> tuple[list[dict], list[dict], int | None]:
    """Same shape as scenarios.build_stream, generated by real model calls."""
    client = client or _client()
    normal = LIVE_CONFIGS["control"]
    baseline = generate_live(items, normal, n_baseline, seed, 0, client)
    pre = generate_live(items, normal, n_pre, seed + 1, n_baseline, client)
    if scenario == "control":
        post = generate_live(items, normal, n_post, seed + 2, n_baseline + n_pre, client)
        return baseline, pre + post, None
    post = generate_live(
        items, LIVE_CONFIGS[scenario], n_post, seed + 2, n_baseline + n_pre, client
    )
    return baseline, pre + post, n_pre
